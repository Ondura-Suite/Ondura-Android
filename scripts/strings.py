def esc(v: str) -> str:
    return v.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

root = Path(__file__).resolve().parent.parent / "mail/src/main/res"
for idx, folder in enumerate(["values", "values-de", "values-fr"]):
    out = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by scripts/strings.py – edit the table there. -->", "<resources>"]
    for key, langs in S.items():
        extra = ' translatable="false"' if idx == 0 and key == "app_name" else ""
        if idx > 0 and key == "app_name":
            continue
        out.append(f'    <string name="{key}"{extra}>{esc(langs[idx])}</string>')
    out.append("</resources>\n")
    d = root / folder
    d.mkdir(parents=True, exist_ok=True)
    (d / "strings.xml").write_text("\n".join(out), encoding="utf-8")
print(f"{len(S)} strings written")
